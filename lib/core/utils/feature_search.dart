/// **MENÜ İÇİ ARAMA** (kullanıcı isteği 2026-11-23: "panellerde, menülerde iç
/// arama olmalı; yalnız harf eşleşmesiyle değil, işlev özellikleriyle de
/// arama yapılabilmeli; özellik sözlüğü çok geniş olmalı — Türkçe, İngilizce
/// ve diğer dillerde").
///
/// Bir menü maddesi ([id] + görünen [label]) şu sözcüklerle bulunur:
///  1. adının sözcükleri (ön ek: "hes" → "Hesap makinesi");
///  2. kimliği;
///  3. **işlev sözlüğü** [kFeatureConcepts]: maddenin kimliği ya da adı bir
///     kavrama bağlanırsa o kavramın BÜTÜN dillerdeki eş anlamlıları
///     ("topla", "calculator", "rechner", "calculadora" → Hesap makinesi).
///
/// Karşılaştırma büyük/küçük harf ve aksan duyarsızdır (ı/i, ş/s, ğ/g, é/e…);
/// 5+ harfli sözcükte tek harf yazım hatası da tutar ("hesp makinasi").
library;

/// Arama için katlama: küçük harf (Türkçe İ/I dahil) + aksansız Latin.
String foldSearch(String s) {
  final out = StringBuffer();
  for (final rune in s.runes) {
    final ch = String.fromCharCode(rune);
    final mapped = _fold[ch];
    if (mapped != null) {
      out.write(mapped);
    } else {
      out.write(ch.toLowerCase());
    }
  }
  return out.toString();
}

const _fold = <String, String>{
  'İ': 'i', 'I': 'i', 'ı': 'i', 'Ş': 's', 'ş': 's', 'Ğ': 'g', 'ğ': 'g', //
  'Ü': 'u', 'ü': 'u', 'Ö': 'o', 'ö': 'o', 'Ç': 'c', 'ç': 'c', //
  'á': 'a', 'à': 'a', 'â': 'a', 'ä': 'a', 'ã': 'a', 'å': 'a', 'Á': 'a', //
  'À': 'a', 'Â': 'a', 'Ä': 'a', 'Ã': 'a', 'é': 'e', 'è': 'e', 'ê': 'e', //
  'ë': 'e', 'É': 'e', 'È': 'e', 'Ê': 'e', 'í': 'i', 'ì': 'i', 'î': 'i', //
  'ï': 'i', 'Í': 'i', 'Î': 'i', 'ó': 'o', 'ò': 'o', 'ô': 'o', 'õ': 'o', //
  'Ó': 'o', 'Ô': 'o', 'ú': 'u', 'ù': 'u', 'û': 'u', 'Ú': 'u', 'Û': 'u', //
  'ñ': 'n', 'Ñ': 'n', 'ß': 'ss', 'œ': 'oe', 'æ': 'ae', 'ÿ': 'y', 'ё': 'е', //
};

final _split = RegExp(r'[\s\-_/·,.:;()…!?&+]+');

List<String> _words(String folded) => [
  for (final w in folded.split(_split))
    if (w.isNotEmpty) w,
];

/// Bir işlev kavramı: bağlandığı menü kimlikleri ve bütün dillerdeki
/// sözcükleri. Sözcüklerden biri maddenin ADINDA geçerse de bağlanır.
typedef FeatureConcept = ({List<String> ids, List<String> words});

class _Compiled {
  _Compiled(this.ids, this.words, this.anchors);
  final Set<String> ids;
  final List<String> words;

  /// Ada bakarak bağlanmak için kullanılan (katlanmış, ≥ 4 harf) sözcükler.
  final List<String> anchors;
}

final List<_Compiled> _compiled = [
  for (final c in kFeatureConcepts)
    _Compiled(
      {for (final id in c.ids) id.toLowerCase()},
      [for (final w in c.words) ...?_wordsOrNull(foldSearch(w))],
      [
        for (final w in c.words)
          if (foldSearch(w) case final f when f.length >= 4) f,
      ],
    ),
];

List<String>? _wordsOrNull(String s) {
  final w = _words(s);
  return w.isEmpty ? null : w;
}

final Map<String, List<String>> _keywordCache = {};

/// Maddenin aranabilir sözcükleri (ad + kimlik + bağlı kavramlar).
List<String> featureKeywords(String id, String label) {
  final key = '$id\u0000$label';
  final cached = _keywordCache[key];
  if (cached != null) return cached;
  final foldedLabel = foldSearch(label);
  final labelWords = _words(foldedLabel);
  final idLower = id.toLowerCase();
  final out = <String>{...labelWords, ..._words(foldSearch(_unCamel(id)))};
  for (final c in _compiled) {
    var hit = c.ids.contains(idLower);
    if (!hit) {
      for (final a in c.anchors) {
        // Çok sözcüklü çapa ("hesap makinesi") adın içinde; tek sözcük ise
        // adın bir sözcüğünün başı ("takvim" → "takvime").
        if (a.contains(' ')
            ? foldedLabel.contains(a)
            : labelWords.any((w) => w.startsWith(a))) {
          hit = true;
          break;
        }
      }
    }
    if (hit) out.addAll(c.words);
  }
  if (_keywordCache.length > 2000) _keywordCache.clear();
  return _keywordCache[key] = out.toList(growable: false);
}

String _unCamel(String id) =>
    id.replaceAllMapped(RegExp('([a-z])([A-Z])'), (m) => '${m[1]} ${m[2]}');

/// [query]'nin maddeye uyma puanı; 0 = uymuyor. Büyük puan önce gelir: adın
/// başı > adın içi > sözlük > yazım hatası.
int featureMatchScore(
  String query, {
  required String id,
  required String label,
}) {
  final tokens = _words(foldSearch(query));
  if (tokens.isEmpty) return 1;
  final foldedLabel = foldSearch(label);
  final labelWords = _words(foldedLabel);
  final keywords = featureKeywords(id, label);
  var total = 0;
  for (final t in tokens) {
    var best = 0;
    if (labelWords.any((w) => w.startsWith(t))) {
      best = foldedLabel.startsWith(t) ? 100 : 80;
    } else if (t.length >= 3 && foldedLabel.contains(t)) {
      best = 60;
    } else if (keywords.any((w) => w.startsWith(t))) {
      best = 50;
    } else if (t.length >= 4 && keywords.any((w) => w.contains(t))) {
      best = 35;
    } else if (t.length >= 5 && keywords.any((w) => _nearPrefix(t, w))) {
      best = 20;
    }
    if (best == 0) return 0;
    total += best;
  }
  return total;
}

bool featureMatches(
  String query, {
  required String id,
  required String label,
}) => featureMatchScore(query, id: id, label: label) > 0;

/// [t] ile [w]'nin aynı boydaki başı arasında en çok bir düzenleme farkı.
bool _nearPrefix(String t, String w) {
  if (w.length < t.length - 1) return false;
  final a = t;
  final b = w.length > t.length + 1 ? w.substring(0, t.length + 1) : w;
  // Levenshtein (kısa dizeler), b'nin her öneki için en iyisi.
  var prev = List<int>.generate(b.length + 1, (j) => j);
  for (var i = 1; i <= a.length; i++) {
    final cur = List<int>.filled(b.length + 1, 0)..[0] = i;
    for (var j = 1; j <= b.length; j++) {
      final cost = a.codeUnitAt(i - 1) == b.codeUnitAt(j - 1) ? 0 : 1;
      cur[j] = [
        prev[j] + 1,
        cur[j - 1] + 1,
        prev[j - 1] + cost,
      ].reduce((x, y) => x < y ? x : y);
    }
    prev = cur;
  }
  final best = prev
      .skip(a.length - 1 < 0 ? 0 : a.length - 1)
      .reduce((x, y) => x < y ? x : y);
  return best <= 1;
}

